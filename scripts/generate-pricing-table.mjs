#!/usr/bin/env node

/**
 * Generate docs/PRICES.md from the built-in price table.
 *
 * The table is generated rather than hand-written so the published page can
 * never drift from the rates the CLI actually charges. Run with --check in CI
 * to fail when the committed page is out of date, when a provider's
 * verification date has aged past its threshold, or when a dated rate change
 * has come due and the table still carries the old price.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PRICES } from '../ts/packages/core/src/pricing.js';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCES_FILE = path.join(repoRoot, 'docs', 'pricing-sources.json');
const OUTPUT_FILE = path.join(repoRoot, 'docs', 'PRICES.md');
const check = process.argv.includes('--check');

const sources = JSON.parse(readFileSync(SOURCES_FILE, 'utf8'));
const failures = [];

function today() {
  return process.env.TOKIMETER_PRICING_TODAY || new Date().toISOString().slice(0, 10);
}

function daysBetween(fromIso, toIso) {
  return Math.floor((Date.parse(toIso) - Date.parse(fromIso)) / 86400000);
}

// Keep at least two decimals for readability and up to four so a rate like
// $0.075 is shown exactly rather than rounded on a page about accuracy.
function usd(value) {
  if (typeof value !== 'number' || Number.isNaN(value)) return '—';
  const [whole, fraction = ''] = value.toFixed(4).replace(/0+$/, '').split('.');
  return `$${whole}.${fraction.padEnd(2, '0')}`;
}

// The price table uses 0 to mean "provider publishes no rate for this bucket",
// which is not the same as free.
function cacheRate(value) {
  return value ? usd(value) : '_not published_';
}

function cacheWriteFor(price) {
  // The engine falls back to 1.25x input when a provider publishes no explicit
  // cache-write rate, so show that derivation rather than an invented number.
  if (typeof price.cacheWrite === 'number') return usd(price.cacheWrite);
  return `${usd(price.input * 1.25)} (1.25× input)`;
}

function providerMeta(providerId) {
  return sources.providers[providerId] || {
    label: providerId,
    source: null,
    url: null,
    verified: null,
    note: 'This provider is missing from docs/pricing-sources.json.',
  };
}

function sourceCell(meta) {
  if (!meta.source) return '_not recorded_';
  return meta.url ? `[${meta.source}](${meta.url})` : meta.source;
}

function buildPage() {
  const now = today();
  const byProvider = new Map();
  for (const price of PRICES) {
    if (!byProvider.has(price.provider)) byProvider.set(price.provider, []);
    byProvider.get(price.provider).push(price);
  }

  const sourced = [...byProvider.keys()].filter((id) => providerMeta(id).verified);
  const unsourced = [...byProvider.keys()].filter((id) => !providerMeta(id).verified);
  const disputed = unsourced.filter((id) => providerMeta(id).disputed);

  const lines = [];
  lines.push('<!-- Generated by scripts/generate-pricing-table.mjs. Do not edit by hand. -->');
  lines.push('# AI coding model prices');
  lines.push('');
  lines.push('Every rate Tokimeter uses to value token usage, in USD per 1M tokens, with');
  lines.push('the source and verification date for each provider.');
  lines.push('');
  lines.push('These are **API list prices**, not what a subscription costs. Tokimeter applies');
  lines.push('them to locally recorded token counts to produce an API-equivalent value, which');
  lines.push('it marks `~$` precisely because it is not a bill. See');
  lines.push('[the pricing methodology](PRICING.md) for how that distinction is enforced.');
  lines.push('');
  lines.push(`${PRICES.length} models across ${byProvider.size} providers.`);
  lines.push(`${sourced.length} providers are sourced and verified.`);
  if (disputed.length) {
    lines.push('');
    lines.push(`> **${disputed.length} providers below carry disputed rates.** ` +
      `${disputed.map((id) => providerMeta(id).label).join(', ')} were checked against their published ` +
      'pricing and did not match. Their sections say so, and their numbers should not be relied on until ' +
      'they are corrected. They are listed here rather than quietly omitted because hiding them would be ' +
      'the dishonest option.');
  }
  lines.push('');

  for (const providerId of [...sourced, ...unsourced]) {
    const meta = providerMeta(providerId);
    const models = byProvider.get(providerId);
    lines.push(`## ${meta.label}`);
    lines.push('');
    lines.push(`**Source:** ${sourceCell(meta)}  `);
    lines.push(`**Verified:** ${meta.verified || '_not recorded_'}`);
    if (meta.note) {
      lines.push('');
      lines.push(meta.note);
    }
    if (meta.disputed) {
      const against = meta.disputed.against
        ? `[published pricing](${meta.disputed.against})`
        : 'published pricing';
      lines.push('');
      lines.push(`> **These rates are disputed.** Checked ${meta.disputed.checked} against ${against}.`);
      lines.push('>');
      lines.push(`> ${meta.disputed.summary}`);
      lines.push('>');
      lines.push('> Treat the rates below as unreliable until they are corrected.');
    }
    lines.push('');
    lines.push('| Model | Input | Cache read | Cache write | Output |');
    lines.push('|---|---|---|---|---|');
    for (const price of models) {
      lines.push(`| \`${price.model}\` | ${usd(price.input)} | ${cacheRate(price.cached)} | ${cacheWriteFor(price)} | ${usd(price.output)} |`);
    }
    lines.push('');
  }

  if (sources.scheduledChanges.length) {
    lines.push('## Scheduled rate changes');
    lines.push('');
    lines.push('Dated changes a provider has already announced. CI fails once one of these');
    lines.push('comes due and the table still carries the old rate, so a promotional price');
    lines.push('cannot quietly go stale.');
    lines.push('');
    lines.push('| Model | Effective | Change |');
    lines.push('|---|---|---|');
    for (const change of sources.scheduledChanges) {
      lines.push(`| \`${change.model}\` | ${change.effective} | ${change.note} |`);
    }
    lines.push('');
  }

  lines.push('## How to read this');
  lines.push('');
  lines.push('- A model missing from this table is **unpriced**. Tokimeter excludes unpriced');
  lines.push('  models from priced totals rather than guessing a rate.');
  lines.push('- Cache write shows `1.25× input` where a provider publishes no explicit rate;');
  lines.push('  that is the documented fallback, not a published price.');
  lines.push('- A provider marked `not recorded` still has working rates, but the source and');
  lines.push('  verification date were never captured. Treat those as lower confidence.');
  lines.push('- Local overrides in `~/.tokimeter/pricing.json` and the opt-in community feed');
  lines.push('  take precedence in that order and are not shown here.');
  lines.push('');
  lines.push(`_Generated ${now} from \`ts/packages/core/src/pricing.js\`._`);
  lines.push('');
  return lines.join('\n');
}

function runChecks() {
  const now = today();
  for (const [providerId, meta] of Object.entries(sources.providers)) {
    if (!meta.verified) continue;
    const age = daysBetween(meta.verified, now);
    if (age >= sources.stalenessFailDays) {
      failures.push(`${providerId} pricing was last verified ${age} days ago (${meta.verified}); re-verify against ${meta.source || 'the provider docs'}`);
    } else if (age >= sources.stalenessWarnDays) {
      console.warn(`  ! ${providerId} pricing was last verified ${age} days ago (${meta.verified})`);
    }
  }

  for (const change of sources.scheduledChanges) {
    if (Date.parse(now) < Date.parse(change.effective)) continue;
    const price = PRICES.find((entry) => entry.model === change.model);
    if (!price) {
      failures.push(`scheduled change for ${change.model} is due but that model is no longer in the price table`);
      continue;
    }
    const expected = change.expectedAfter || {};
    for (const field of ['input', 'output']) {
      if (typeof expected[field] === 'number' && price[field] !== expected[field]) {
        failures.push(`${change.model} ${field} is still ${price[field]} after ${change.effective}; expected ${expected[field]} (${change.note})`);
      }
    }
  }

  const known = new Set(Object.keys(sources.providers));
  for (const price of PRICES) {
    if (!known.has(price.provider)) {
      failures.push(`provider "${price.provider}" has no entry in docs/pricing-sources.json`);
      known.add(price.provider);
    }
  }
}

const page = buildPage();
runChecks();

if (check) {
  let committed = '';
  try {
    committed = readFileSync(OUTPUT_FILE, 'utf8');
  } catch {
    failures.push('docs/PRICES.md is missing; run: node scripts/generate-pricing-table.mjs');
  }
  // The generated-on line moves every day, so compare everything above it.
  const stripDate = (text) => text.replace(/^_Generated \d{4}-\d{2}-\d{2} from .*$/m, '');
  if (committed && stripDate(committed) !== stripDate(page)) {
    failures.push('docs/PRICES.md is out of date; run: node scripts/generate-pricing-table.mjs');
  }
} else {
  writeFileSync(OUTPUT_FILE, page);
  console.log(`  Wrote docs/PRICES.md (${PRICES.length} models, ${Object.keys(sources.providers).length} providers)`);
}

if (failures.length) {
  console.error('\nPricing table check failed:');
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}
if (check) console.log('  Pricing table is current, sourced, and no dated change is overdue.');
